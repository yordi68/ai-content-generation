"""Heritage Short Studio: a local web app over the film pipeline.

One film at a time is generated by a background worker. Every stage is the same
CLI script `make film` runs, pointed at a project workspace with PROJECT_ROOT,
so the web app cannot drift from the pipeline it exposes.
"""

import asyncio
import json
import os
import queue
import subprocess
import sys
import threading
import time
import uuid
from pathlib import Path
from typing import Literal

sys.path.insert(0, str(Path(__file__).resolve().parent))

from fastapi import FastAPI, HTTPException, Request
from fastapi.responses import FileResponse, HTMLResponse, StreamingResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel

import studio
from validate import REPO_ROOT

PYTHON = sys.executable
WEB_DIR = REPO_ROOT / "web"
MAX_EVENTS = 4000

app = FastAPI(title="Heritage Short Studio")
app.mount("/static", StaticFiles(directory=str(WEB_DIR)), name="static")


class CreateProjectBody(BaseModel):
    title: str = ""
    mode: Literal["prompt", "script"] = "prompt"
    story_prompt: str = ""
    script: str = ""
    language: Literal["am", "en"] = "am"
    style: Literal["storybook", "cinematic", "papercut"] = "storybook"


class ShotEditBody(BaseModel):
    narration: str | None = None
    subtitle: str | None = None
    picture: str | None = None
    characters: list[str] | None = None
    motion: dict | None = None
    seed: int | None = None
    reason: str | None = None


class Job:
    def __init__(self, slug, stages, shots=None, aspects=None):
        self.id = uuid.uuid4().hex[:12]
        self.slug = slug
        self.stages = list(stages)
        self.shots = sorted(shots) if shots else None
        self.aspects = aspects
        self.status = "queued"
        self.stage = None
        self.error = None
        self.created_at = studio.now_iso()
        self.started_at = None
        self.finished_at = None
        self.events = []
        self.lock = threading.Lock()
        self.proc = None
        self.cancel_requested = False

    def emit(self, event):
        with self.lock:
            self.events.append(event)
            if len(self.events) > MAX_EVENTS:
                del self.events[: len(self.events) - MAX_EVENTS]

    def snapshot(self):
        with self.lock:
            return {
                "id": self.id,
                "slug": self.slug,
                "stages": self.stages,
                "shots": self.shots,
                "aspects": self.aspects,
                "status": self.status,
                "stage": self.stage,
                "error": self.error,
                "created_at": self.created_at,
                "started_at": self.started_at,
                "finished_at": self.finished_at,
            }


JOBS = {}
LATEST = {}
RUNNING = {}
QUEUE = queue.Queue()


def persist_job(job):
    if job.slug == studio.SHOWCASE_SLUG:
        return
    try:
        meta = studio.read_meta(job.slug)
        meta["job"] = job.snapshot()
        studio.write_meta(job.slug, meta)
    except (KeyError, OSError, json.JSONDecodeError):
        pass


def enqueue(slug, stages, shots=None, aspects=None):
    if slug == studio.SHOWCASE_SLUG:
        raise HTTPException(status_code=403, detail="The showcase film is read-only. Create a new film to edit.")
    active = RUNNING.get(slug)
    if active and active.status in ("queued", "running"):
        raise HTTPException(status_code=409, detail="This film already has a build running.")
    job = Job(slug, stages, shots, aspects)
    JOBS[job.id] = job
    LATEST[slug] = job
    RUNNING[slug] = job
    persist_job(job)
    QUEUE.put(job.id)
    return job


def stage_command(stage, job):
    command = [PYTHON, str(REPO_ROOT / "pipeline" / f"{stage}.py")]
    if job.shots and stage in ("narration", "keyframes", "shots"):
        command += ["--shots", ",".join(str(shot) for shot in job.shots)]
    if job.aspects and stage == "shots":
        command += ["--aspect", ",".join(job.aspects)]
    return command


def run_stage(job, stage):
    root = studio.project_root(job.slug)
    env = os.environ.copy()
    env["PROJECT_ROOT"] = str(root)
    env["PROJECT_SLUG"] = job.slug
    env["PYTHONUNBUFFERED"] = "1"

    job.stage = stage
    job.emit({"type": "stage", "stage": stage, "status": "start"})
    persist_job(job)

    log_path = root / "job.log"
    with log_path.open("a", encoding="utf-8") as log:
        log.write(f"\n=== {studio.now_iso()} {stage} ===\n")
        log.flush()
        process = subprocess.Popen(
            stage_command(stage, job),
            cwd=str(REPO_ROOT),
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
        )
        job.proc = process
        assert process.stdout is not None
        for line in process.stdout:
            line = line.rstrip("\n")
            if not line:
                continue
            log.write(line + "\n")
            log.flush()
            job.emit({"type": "log", "line": line})
            if job.cancel_requested and process.poll() is None:
                process.terminate()
        code = process.wait()
        job.proc = None

    if job.cancel_requested:
        raise RuntimeError("cancelled")
    if code != 0:
        raise RuntimeError(f"{stage} exited with code {code}")

    job.emit({"type": "stage", "stage": stage, "status": "done"})
    job.emit({"type": "refresh"})


def run_job(job):
    job.status = "running"
    job.started_at = studio.now_iso()
    job.emit({"type": "job", "status": "running"})
    persist_job(job)
    try:
        for stage in job.stages:
            if job.cancel_requested:
                raise RuntimeError("cancelled")
            run_stage(job, stage)
        job.status = "done"
        job.stage = None
        try:
            studio.clear_build_state(job.slug, job.shots)
        except (KeyError, OSError, json.JSONDecodeError):
            pass
        job.emit({"type": "done"})
    except Exception as exc:  # noqa: BLE001 - the message is shown to the user
        if job.cancel_requested:
            job.status = "cancelled"
            job.error = None
            job.emit({"type": "cancelled"})
        else:
            job.status = "failed"
            job.error = str(exc)
            job.emit({"type": "failed", "error": str(exc)})
    finally:
        job.finished_at = studio.now_iso()
        RUNNING.pop(job.slug, None)
        persist_job(job)


def worker():
    while True:
        job_id = QUEUE.get()
        job = JOBS.get(job_id)
        if job is not None:
            run_job(job)
        QUEUE.task_done()


threading.Thread(target=worker, daemon=True, name="film-worker").start()


def recover_interrupted_jobs():
    if not studio.PROJECTS_DIR.exists():
        return
    for path in studio.PROJECTS_DIR.iterdir():
        if not path.is_dir() or not (path / studio.META_NAME).exists():
            continue
        try:
            meta = studio.read_meta(path.name)
        except (KeyError, json.JSONDecodeError):
            continue
        if meta.get("job", {}).get("status") in ("queued", "running"):
            meta["job"] = {
                "status": "failed",
                "stage": None,
                "error": "Interrupted by a studio restart. Press Generate to resume; finished stages are cached.",
                "stages": [],
            }
            studio.write_meta(path.name, meta)


recover_interrupted_jobs()


def summary_with_job(slug):
    try:
        summary = studio.project_summary(slug)
    except KeyError:
        raise HTTPException(status_code=404, detail="No such film.")
    latest = LATEST.get(slug)
    summary["job"] = latest.snapshot() if latest else summary["meta"].get("job", {})
    return summary


