@app.post("/api/projects")
def api_create(body: CreateProjectBody):
    title = body.title.strip()
    if len(title) > 80:
        raise HTTPException(status_code=422, detail="Title must be 80 characters or fewer.")
    if body.mode == "prompt" and len(body.story_prompt.strip()) < 10:
        raise HTTPException(status_code=422, detail="Write at least a sentence (10 characters) for the story prompt.")
    if body.mode == "script" and len(body.script.strip()) < 80:
        raise HTTPException(status_code=422, detail="Paste at least a short script (80 characters) to divide into shots.")
    try:
        slug = studio.create_project(title, body.mode, body.story_prompt, body.script, body.language, body.style)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=str(exc))
    job = enqueue(
        slug,
        ["script", "narration", "keyframes", "shots", "music", "assemble"],
    )
    return {"slug": slug, "job": job.snapshot()}


@app.get("/api/projects/{slug}")
def api_project(slug: str):
    return summary_with_job(slug)


@app.patch("/api/projects/{slug}/shots/{shot_id}")
def api_edit_shot(slug: str, shot_id: int, body: ShotEditBody):
    fields = body.model_dump(exclude_unset=True)
    if not fields:
        raise HTTPException(status_code=422, detail="Nothing to save.")
    try:
        _, stages = studio.apply_shot_edit(slug, shot_id, fields)
    except PermissionError as exc:
        raise HTTPException(status_code=403, detail=str(exc))
    except (KeyError, ValueError) as exc:
        raise HTTPException(status_code=422, detail=str(exc))
    job = enqueue(slug, stages, shots=[shot_id]) if stages else None
    return {"stages": stages, "job": job.snapshot() if job else None}


@app.post("/api/projects/{slug}/draft")
def api_draft(slug: str):
    try:
        studio.project_root(slug)
    except KeyError:
        raise HTTPException(status_code=404, detail="No such film.")
    job = enqueue(slug, ["script", "narration", "keyframes", "shots", "music", "assemble"])
    return {"job": job.snapshot()}


@app.post("/api/projects/{slug}/generate")
def api_generate(slug: str):
    try:
        board = studio.storyboard(slug)
    except KeyError:
        raise HTTPException(status_code=404, detail="No such film.")
    if board is None:
        raise HTTPException(status_code=409, detail="This film has no storyboard yet.")
    job = enqueue(slug, ["narration", "keyframes", "shots", "music", "assemble"])
    return {"job": job.snapshot()}


@app.post("/api/projects/{slug}/assemble")
def api_assemble(slug: str):
    try:
        board = studio.storyboard(slug)
        summary = studio.project_summary(slug)
    except KeyError:
        raise HTTPException(status_code=404, detail="No such film.")
    if board is None:
        raise HTTPException(status_code=409, detail="This film has no storyboard yet.")
    if any(shot["missing"] for shot in summary["shots"]):
        raise HTTPException(
            status_code=409,
            detail="Some shots have no media yet. Press Generate everything first.",
        )
    if any(shot["stale"] for shot in summary["shots"]):
        raise HTTPException(
            status_code=409,
            detail="Some shot edits still need regenerating. Retry the shot or press Generate everything.",
        )
    job = enqueue(slug, ["assemble"])
    return {"job": job.snapshot()}


@app.post("/api/projects/{slug}/cancel")
def api_cancel(slug: str):
    job = RUNNING.get(slug)
    if not job or job.status not in ("queued", "running"):
        raise HTTPException(status_code=409, detail="Nothing is running for this film.")
    job.cancel_requested = True
    job.emit({"type": "log", "line": "Cancel requested; stopping after this step."})
    if job.proc and job.proc.poll() is None:
        job.proc.terminate()
    return {"job": job.snapshot()}


@app.delete("/api/projects/{slug}")
def api_delete(slug: str):
    if RUNNING.get(slug):
        raise HTTPException(status_code=409, detail="Wait for the running build to finish before deleting.")
    try:
        studio.delete_project(slug)
    except PermissionError as exc:
        raise HTTPException(status_code=403, detail=str(exc))
    except KeyError:
        raise HTTPException(status_code=404, detail="No such film.")
    LATEST.pop(slug, None)
    return {"deleted": slug}


@app.get("/api/projects/{slug}/events")
async def api_events(slug: str, request: Request):
    job = LATEST.get(slug)
    if job is None:
        async def idle():
            yield 'data: {"type":"idle"}\n\n'

        return StreamingResponse(idle(), media_type="text/event-stream")

    async def stream():
        index = 0
        idle_ticks = 0
        while True:
            if await request.is_disconnected():
                break
            with job.lock:
                pending = job.events[index:]
                index = len(job.events)
                status = job.status
            if pending:
                idle_ticks = 0
                for event in pending:
                    yield f"data: {json.dumps(event, ensure_ascii=False)}\n\n"
            else:
                idle_ticks += 1
                if idle_ticks % 25 == 0:
                    yield ": ping\n\n"
            if status in ("done", "failed", "cancelled") and index >= len(job.events):
                break
            await asyncio.sleep(0.4)
        yield 'data: {"type":"stream_end"}\n\n'

    return StreamingResponse(
        stream(),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


@app.get("/api/projects/{slug}/media/{relpath:path}")
def api_media(slug: str, relpath: str):
    try:
        base = (studio.project_root(slug) / "outputs").resolve()
    except KeyError:
        raise HTTPException(status_code=404, detail="No such film.")
    target = (base / relpath).resolve()
    if target != base and base not in target.parents:
        raise HTTPException(status_code=404, detail="Not found.")
    if target.suffix.lower() not in {".mp4", ".wav", ".jpg", ".png"}:
        raise HTTPException(status_code=404, detail="Not found.")
    if not target.is_file():
        raise HTTPException(status_code=404, detail="Not generated yet.")
    return FileResponse(target)


@app.get("/api/projects/{slug}/storyboard")
def api_storyboard(slug: str):
    try:
        path = studio.project_root(slug) / "storyboard.json"
    except KeyError:
        raise HTTPException(status_code=404, detail="No such film.")
    if not path.is_file():
        raise HTTPException(status_code=404, detail="This film has no storyboard yet.")
    return FileResponse(path, media_type="application/json", filename=f"{slug}-storyboard.json")


@app.get("/api/projects/{slug}/log")
def api_log(slug: str):
    try:
        path = studio.project_root(slug) / "job.log"
    except KeyError:
        raise HTTPException(status_code=404, detail="No such film.")
    if not path.is_file():
        return {"log": ""}
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()[-400:]
    return {"log": "\n".join(lines)}
